namespace AnchorPS5.App;

/// <summary>
/// Glifos de la interfaz. En Windows la app usa la fuente Segoe MDL2 (no disponible en
/// Linux), así que aquí se mapean a caracteres Unicode que pinta la fuente Inter: mismos
/// significados, sin depender de una fuente de iconos propietaria.
/// </summary>
public static class Glyphs
{
    public const string Catalog = "\u2630";  // ☰  (list)
    public const string Download = "\u2B07";  // ⬇
    public const string Sync = "\u21BB";      // ↻
    public const string Star = "\u2605";      // ★
    public const string Guide = "\u2753";     // ❓
    public const string Info = "\u2139";      // ℹ
    public const string Home = "\u2302";      // ⌂
    public const string Refresh = "\u27F3";   // ⟳
    public const string Check = "\u2713";     // ✓
    public const string Up = "\u2191";        // ↑
    public const string Folder = "\u2302";    // ⌂
    public const string Delete = "\u2715";    // ✕
    public const string Box = "\u25A3";       // ▣
    public const string Person = "\u263A";    // ☺
    public const string ChevronDown = "\u2304"; // ⌄
    public const string File = "\u2261";      // ≡
    public const string Back = "\u2190";      // ←
    public const string Version = "\u2299";   // ⊙
    public const string Link = "\u26D3";      // ⛓
    public const string Code = "\u2325";      // ⌥
    public const string Id = "\u2606";        // ☆
    public const string Globe = "\u25CD";     // ◍
    public const string Add = "\uFF0B";       // ＋
    public const string Cancel = "\u2715";    // ✕
}
